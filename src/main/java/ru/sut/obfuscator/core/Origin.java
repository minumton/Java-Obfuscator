package ru.sut.obfuscator.core;

/**
 * Происхождение объявления, на которое ссылается имя в коде.
 */
public enum Origin {

    /** Объявление находится в обрабатываемых файлах — имя можно заменять. */
    USER,

    /** Объявление принадлежит JDK или библиотеке — имя менять нельзя. */
    EXTERNAL,

    /** Определить объявление не удалось — имя нельзя менять нигде. */
    UNKNOWN
}
